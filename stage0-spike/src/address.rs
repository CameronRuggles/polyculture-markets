//! Spike 1: Monero destination validation (spec §3 invariant 7, §11).
//! Uses the maintained `monero` crate (monero-rs) — never hand-rolled parsing.

use std::str::FromStr;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Network {
    Mainnet,
    Stagenet,
    Testnet,
}

impl From<monero::Network> for Network {
    fn from(n: monero::Network) -> Self {
        match n {
            monero::Network::Mainnet => Network::Mainnet,
            monero::Network::Stagenet => Network::Stagenet,
            monero::Network::Testnet => Network::Testnet,
        }
    }
}
impl From<Network> for monero::Network {
    fn from(n: Network) -> Self {
        match n {
            Network::Mainnet => monero::Network::Mainnet,
            Network::Stagenet => monero::Network::Stagenet,
            Network::Testnet => monero::Network::Testnet,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DestinationInfo {
    pub network: Network,
    pub kind: String, // "subaddress" for the only accepted kind
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reject {
    Parse,
    WrongNetwork,
    NotSubaddress,
}

/// Accept only a subaddress on the expected network (spec §3.7).
/// Primary/standard and integrated addresses are rejected, as are
/// wrong-network subaddresses and anything unparseable (incl. bad checksum —
/// the `monero` crate verifies the base58 checksum and key validity in FromStr).
pub fn validate_destination(address: &str, expected: Network) -> Result<DestinationInfo, Reject> {
    let parsed = monero::Address::from_str(address).map_err(|_| Reject::Parse)?;
    let net = Network::from(parsed.network);
    if net != expected {
        return Err(Reject::WrongNetwork);
    }
    match parsed.addr_type {
        monero::AddressType::SubAddress => Ok(DestinationInfo {
            network: net,
            kind: "subaddress".to_string(),
        }),
        _ => Err(Reject::NotSubaddress),
    }
}

#[cfg(test)]
pub(crate) mod testutil {
    use super::*;
    /// Build an address of a given type/network from fixed private keys
    /// (public keys derived through the crate, guaranteeing valid points).
    pub fn make_addr(net: Network, kind: &str) -> String {
        use monero::util::key::PrivateKey;
        let mut spend = [0u8; 32];
        spend[0] = 7;
        let mut view = [0u8; 32];
        view[0] = 9;
        let spend_key = PrivateKey::from_slice(&spend).unwrap();
        let view_key = PrivateKey::from_slice(&view).unwrap();
        let public_spend = monero::PublicKey::from_private_key(&spend_key);
        let public_view = monero::PublicKey::from_private_key(&view_key);
        let n: monero::Network = net.into();
        let addr = match kind {
            "standard" => monero::Address::standard(n, public_spend, public_view),
            "subaddress" => monero::Address::subaddress(n, public_spend, public_view),
            "integrated" => monero::Address::integrated(
                n,
                public_spend,
                public_view,
                monero::util::address::PaymentId([1, 2, 3, 4, 5, 6, 7, 8]),
            ),
            _ => panic!("unknown kind"),
        };
        addr.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::testutil::make_addr;
    use super::*;

    #[test]
    fn accepts_mainnet_subaddress() {
        let a = make_addr(Network::Mainnet, "subaddress");
        let info = validate_destination(&a, Network::Mainnet).expect("valid subaddress");
        assert_eq!(info.kind, "subaddress");
        assert_eq!(info.network, Network::Mainnet);
    }

    #[test]
    fn rejects_standard_and_integrated() {
        for kind in ["standard", "integrated"] {
            let a = make_addr(Network::Mainnet, kind);
            assert_eq!(
                validate_destination(&a, Network::Mainnet),
                Err(Reject::NotSubaddress),
                "{kind} must be rejected"
            );
        }
    }

    #[test]
    fn rejects_wrong_network() {
        let a = make_addr(Network::Stagenet, "subaddress");
        assert_eq!(
            validate_destination(&a, Network::Mainnet),
            Err(Reject::WrongNetwork)
        );
        let info = validate_destination(&a, Network::Stagenet).expect("stagenet ok");
        assert_eq!(info.network, Network::Stagenet);
    }

    #[test]
    fn external_fixture_from_official_wallet_rpc_docs() {
        // Address string published in the official Monero wallet RPC docs
        // (get_tx_proof example). Not generated by this crate — an external
        // fixture proving the parser handles real-world address strings.
        // It is a stagenet subaddress.
        let a = "7BnERTpvL5MbCLtj5n9No7J5oE5hHiB3tVCK5cjSvCsYWD2WRJLFuWeKTLiXo5QJqt2ZwUaLy2Vh1Ad51K7FNgqcHgjW85o";
        let info = validate_destination(a, Network::Stagenet).expect("docs fixture must validate");
        assert_eq!(info.kind, "subaddress");
        assert_eq!(validate_destination(a, Network::Mainnet), Err(Reject::WrongNetwork));
    }

    #[test]
    fn rejects_garbage_and_bad_checksum() {
        assert_eq!(validate_destination("not an address", Network::Mainnet), Err(Reject::Parse));
        let a = make_addr(Network::Mainnet, "subaddress");
        let mut bad = a.clone();
        let last = bad.pop().unwrap();
        bad.push(if last == '1' { '2' } else { '1' });
        assert_eq!(validate_destination(&bad, Network::Mainnet), Err(Reject::Parse));
    }
}
